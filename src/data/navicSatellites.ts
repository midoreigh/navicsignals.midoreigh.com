export interface Satellite {
  id: string;
  name: string;
  prn: number;
  constellation: 'NavIC' | 'GPS' | 'Galileo' | 'BeiDou' | 'GLONASS' | 'QZSS';
  orbitType: 'GEO' | 'GSO' | 'MEO' | 'IGSO';
  frequencies: string[];
  azimuth: number; // 0 - 360 degrees
  elevation: number; // 0 - 90 degrees
  cn0DbHz: number; // Signal strength 10 - 50 dB-Hz
  usedInFix: boolean;
  status: 'Healthy' | 'Active' | 'Modernized';
  launchYear: number;
  atomicClock: 'Rubidium' | 'Passive Hydrogen Maser' | 'Cesium';
  orbitalLocation?: string;
  notes?: string;
}

